// Copies ABIs and Sepolia addresses from ../contracts into a typed module, so the UI never drifts from the chain.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const root = new URL("../../contracts/", import.meta.url);
const names = ["DeepSecretGame", "PearlCoin", "SecretFishNFT"];
let out = "// Generated by scripts/sync-contracts.mjs from ../contracts. Do not edit.\n\n";
for (const n of names) {
  const art = JSON.parse(readFileSync(new URL(`artifacts/contracts/${n}.sol/${n}.json`, root)));
  const dep = new URL(`deployments/sepolia/${n}.json`, root);
  const address = existsSync(dep) ? JSON.parse(readFileSync(dep)).address : "0x0000000000000000000000000000000000000000";
  out += `export const ${n} = {\n  address: "${address}",\n  abi: ${JSON.stringify(art.abi)},\n} as const;\n\n`;
}
writeFileSync(new URL("../src/generated/contracts.ts", import.meta.url), out);
console.log(`synced ${names.join(", ")}`);
